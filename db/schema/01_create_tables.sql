CREATE TABLE SECTOARE (
    id_sector INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nume_sector VARCHAR2(100) NOT NULL UNIQUE,
    descriere VARCHAR2(500)
);

CREATE TABLE ACTIVE (
    id_activ INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_sector INT NOT NULL,
    simbol_ticker VARCHAR2(10) NOT NULL UNIQUE,
    denumire_companie VARCHAR2(150) NOT NULL,
    tip_activ VARCHAR2(20) CHECK (tip_activ IN ('ACTIUNE', 'ETF', 'OBLIGATIUNE')),
    CONSTRAINT fk_active_sectoare FOREIGN KEY (id_sector) REFERENCES SECTOARE(id_sector)
);

CREATE TABLE COTATII_ZILNICE (
    id_cotatie INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_activ INT NOT NULL,
    data_cotatie DATE NOT NULL,
    pret_deschidere NUMBER(10,2) CHECK (pret_deschidere > 0),
    pret_inchidere NUMBER(10,2) CHECK (pret_inchidere > 0),
    pret_maxim NUMBER(10,2),
    pret_minim NUMBER(10,2),
    volum NUMBER(15,0) CHECK (volum >= 0),
    CONSTRAINT fk_cotatii_active FOREIGN KEY (id_activ) REFERENCES ACTIVE(id_activ),
    CONSTRAINT uk_activ_data UNIQUE (id_activ, data_cotatie)
);

CREATE TABLE UTILIZATORI (
    id_utilizator INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nume VARCHAR2(100) NOT NULL,
    email VARCHAR2(120) NOT NULL UNIQUE,
    parola_hash VARCHAR2(255) NOT NULL,
    rol VARCHAR2(20) DEFAULT 'INVESTITOR' CHECK (rol IN ('INVESTITOR', 'ADMIN')),
    data_inregistrarii TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE PORTOFOLII (
    id_portofoliu INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_utilizator INT NOT NULL,
    denumire VARCHAR2(100) NOT NULL,
    moneda VARCHAR2(3) DEFAULT 'USD',
    sold_cash NUMBER(12,2) DEFAULT 0 CHECK (sold_cash >= 0),
    data_crearii TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_portofolii_utilizatori FOREIGN KEY (id_utilizator) REFERENCES UTILIZATORI(id_utilizator)
);

CREATE TABLE ORDINE (
    id_ordin INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_portofoliu INT NOT NULL,
    id_activ INT NOT NULL,
    tip_ordin VARCHAR2(10) CHECK (tip_ordin IN ('BUY', 'SELL')),
    cantitate_solicitata INT CHECK (cantitate_solicitata > 0),
    pret_limita NUMBER(10,2) CHECK (pret_limita > 0),
    status VARCHAR2(20) DEFAULT 'PLASAT' CHECK (status IN ('PLASAT', 'EXECUTAT', 'ANULAT')),
    data_plasarii TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_ordine_portofolii FOREIGN KEY (id_portofoliu) REFERENCES PORTOFOLII(id_portofoliu),
    CONSTRAINT fk_ordine_active FOREIGN KEY (id_activ) REFERENCES ACTIVE(id_activ)
);

CREATE TABLE TRANZACTII (
    id_tranzactie INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_ordin INT NOT NULL,
    cantitate_executata INT CHECK (cantitate_executata > 0),
    pret_executie NUMBER(10,2) CHECK (pret_executie > 0),
    comision NUMBER(8,2) DEFAULT 0 CHECK (comision >= 0),
    data_executiei TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_tranzactii_ordine FOREIGN KEY (id_ordin) REFERENCES ORDINE(id_ordin)
);

CREATE TABLE POZITII (
    id_pozitie INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_portofoliu INT NOT NULL,
    id_activ INT NOT NULL,
    cantitate_totala INT CHECK (cantitate_totala >= 0),
    pret_mediu_achizitie NUMBER(10,2) CHECK (pret_mediu_achizitie >= 0),
    CONSTRAINT fk_pozitii_portofolii FOREIGN KEY (id_portofoliu) REFERENCES PORTOFOLII(id_portofoliu),
    CONSTRAINT fk_pozitii_active FOREIGN KEY (id_activ) REFERENCES ACTIVE(id_activ),
    CONSTRAINT uk_portofoliu_activ UNIQUE (id_portofoliu, id_activ)
);

CREATE TABLE DIVIDENDE (
    id_dividend INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_activ INT NOT NULL,
    suma_per_actiune NUMBER(8,2) CHECK (suma_per_actiune > 0),
    data_ex_dividend DATE NOT NULL,
    data_platii DATE NOT NULL,
    CONSTRAINT fk_dividende_active FOREIGN KEY (id_activ) REFERENCES ACTIVE(id_activ)
);

CREATE TABLE INCASARI_DIVIDENDE (
    id_incasare INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_portofoliu INT NOT NULL,
    id_dividend INT NOT NULL,
    suma_totala_incasata NUMBER(10,2) CHECK (suma_totala_incasata > 0),
    data_incasarii DATE DEFAULT SYSDATE,
    CONSTRAINT fk_incasari_portofolii FOREIGN KEY (id_portofoliu) REFERENCES PORTOFOLII(id_portofoliu),
    CONSTRAINT fk_incasari_dividende FOREIGN KEY (id_dividend) REFERENCES DIVIDENDE(id_dividend)
);

CREATE TABLE PREDICTII_IA (
    id_predictie INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_activ INT NOT NULL,
    id_portofoliu INT,
    clasa_risc VARCHAR2(20) CHECK (clasa_risc IN ('SCAZUT', 'MEDIU', 'RIDICAT')),
    orizont_zile INT DEFAULT 30,
    pret_estimat NUMBER(10,2),
    directie_trend VARCHAR2(10) CHECK (directie_trend IN ('BULLISH', 'BEARISH', 'NEUTRU')),
    data_generarii TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_predictii_active FOREIGN KEY (id_activ) REFERENCES ACTIVE(id_activ),
    CONSTRAINT fk_predictii_portofolii FOREIGN KEY (id_portofoliu) REFERENCES PORTOFOLII(id_portofoliu)
);
